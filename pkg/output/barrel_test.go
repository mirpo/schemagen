func TestCollectAllDirectories(t *testing.T) {
	files := []OutputFile{
		{RelativePath: "event.ts"},
		{RelativePath: filepath.Join("events", "header.ts")},
		{RelativePath: filepath.Join("events", "payloads", "v1", "subscribe.ts")},
		{RelativePath: filepath.Join("events", "payloads", "v2", "ping.ts")},
	}

	dirs := CollectAllDirectories(files)

	expectedDirs := []string{
		"events",
		filepath.Join("events", "payloads"),
		filepath.Join("events", "payloads", "v1"),
		filepath.Join("events", "payloads", "v2"),
	}

	require.Len(t, dirs, len(expectedDirs), "should collect expected number of directories")

	for i, expected := range expectedDirs {
		expectedNorm := filepath.FromSlash(expected)
		assert.Equal(t, expectedNorm, dirs[i], "directory should match")
	}
}

