func TestGenerateBarrelFiles_Nested(t *testing.T) {
	plan := &OutputPlan{
		Files: []OutputFile{
			{RelativePath: filepath.Join("events", "event.ts")},
			{RelativePath: filepath.Join("events", "header.ts")},
			{RelativePath: filepath.Join("events", "payloads", "subscribe.ts")},
			{RelativePath: filepath.Join("events", "payloads", "ping.ts")},
		},
	}

	barrels := GenerateBarrelFiles(plan, "ts")

	require.Len(t, barrels, 2, "should generate exactly 2 barrel files")

	foundEventsBarrel := false
	foundPayloadsBarrel := false

	for _, barrel := range barrels {
		if barrel.Path == filepath.Join("events", "index.ts") {
			foundEventsBarrel = true
			assert.Len(t, barrel.Exports, 2, "events/index.ts should have 2 exports")
		}
		if barrel.Path == filepath.Join("events", "payloads", "index.ts") {
			foundPayloadsBarrel = true
			assert.Len(t, barrel.Exports, 2, "events/payloads/index.ts should have 2 exports")
		}
	}

	assert.True(t, foundEventsBarrel, "should find events/index.ts")
	assert.True(t, foundPayloadsBarrel, "should find events/payloads/index.ts")
}

