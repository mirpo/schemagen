func TestGenerateNestedBarrels(t *testing.T) {
	files := []OutputFile{
		{RelativePath: "root.ts"},
		{RelativePath: filepath.Join("a", "file1.ts")},
		{RelativePath: filepath.Join("a", "b", "file2.ts")},
	}

	barrels := GenerateNestedBarrels(files, "ts")

	foundRoot := false
	foundA := false
	foundAB := false

	for _, barrel := range barrels {
		if barrel.Path == "index.ts" {
			foundRoot = true
		}
		if barrel.Path == filepath.Join("a", "index.ts") {
			foundA = true
		}
		if barrel.Path == filepath.Join("a", "b", "index.ts") {
			foundAB = true
		}
	}

	assert.True(t, foundRoot, "should find root index.ts")
	assert.True(t, foundA, "should find a/index.ts")
	assert.True(t, foundAB, "should find a/b/index.ts")
}
