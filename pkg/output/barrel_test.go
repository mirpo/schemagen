func TestGenerateBarrelFiles_TypeScript(t *testing.T) {
	plan := &OutputPlan{
		Files: []OutputFile{
			{RelativePath: "event.ts"},
			{RelativePath: "header.ts"},
			{RelativePath: "meta.ts"},
		},
	}

	barrels := GenerateBarrelFiles(plan, "ts")

	require.Len(t, barrels, 1, "should generate exactly 1 barrel file")
	assert.Equal(t, "index.ts", barrels[0].Path, "barrel path should be index.ts")

	expectedExports := []string{"event", "header", "meta"}
	require.Len(t, barrels[0].Exports, len(expectedExports), "should have expected number of exports")

	for i, expected := range expectedExports {
		assert.Equal(t, expected, barrels[0].Exports[i], "export should match")
	}
}

